import { mkdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { HttpError } from './errors';
import { newShortId } from './ids';

const IMAGE_TYPES: Record<string, string> = {
  'image/png': 'png',
  'image/jpeg': 'jpg',
  'image/webp': 'webp',
};

const MAX_UPLOAD_BYTES = 5 * 1024 * 1024;

/** URL prefix under which files in the cards directory are served. */
export const CARDS_URL_PREFIX = '/cards/';

export function decodeImageDataUrl(dataUrl: string): { buffer: Buffer; ext: string } {
  const match = /^data:([a-z/+-]+);base64,(.+)$/s.exec(dataUrl);
  const ext = match ? IMAGE_TYPES[match[1] ?? ''] : undefined;
  if (!match || !ext) throw HttpError.badRequest('Upload a PNG, JPEG or WebP image.');
  const buffer = Buffer.from(match[2] ?? '', 'base64');
  if (buffer.length === 0) throw HttpError.badRequest('The image is empty.');
  if (buffer.length > MAX_UPLOAD_BYTES)
    throw HttpError.badRequest('The image is larger than 5 MB.');
  return { buffer, ext };
}

/**
 * Stores an image in the cards directory under a generated file name and
 * returns its public URL. Callers pass only ids generated by the hub as
 * `folder`, never user input.
 */
export async function saveCardImage(
  cardsDir: string,
  folder: string,
  buffer: Buffer,
  ext: string,
): Promise<string> {
  const dir = path.join(cardsDir, folder);
  await mkdir(dir, { recursive: true });
  const fileName = `${newShortId()}.${ext}`;
  await writeFile(path.join(dir, fileName), buffer);
  return `${CARDS_URL_PREFIX}${folder}/${fileName}`;
}

/** Deletes a card file previously returned by saveCardImage. Ignores other URLs. */
export async function deleteCardImage(cardsDir: string, url: string | null): Promise<void> {
  if (!url?.startsWith(CARDS_URL_PREFIX)) return;
  const relative = url.slice(CARDS_URL_PREFIX.length);
  const target = path.resolve(cardsDir, relative);
  if (!target.startsWith(path.resolve(cardsDir) + path.sep)) return;
  await rm(target, { force: true });
}

export async function deleteCardFolder(cardsDir: string, folder: string): Promise<void> {
  const target = path.resolve(cardsDir, folder);
  if (!target.startsWith(path.resolve(cardsDir) + path.sep)) return;
  await rm(target, { recursive: true, force: true });
}
